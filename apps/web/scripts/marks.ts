// Builds the asset marks the app draws (Bitcoin, Ether, Bitcoin Cash) from @web3icons/core's mono logos, as inline
// path markup that takes the current colour, and writes src/marks/asset-marks.generated.ts. Gold has no logo of its
// own: its mark (an ingot) is drawn in src/marks/asset.tsx. Run again when the icon package is updated.
// Usage: node scripts/marks.ts
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const TOKENS = ["BTC", "ETH", "BCH"] as const;
const out = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "marks", "asset-marks.generated.ts");

const marks: Record<string, string> = {};
for (const token of TOKENS) {
  const svg = ((await import(`@web3icons/core/svgs/tokens/mono/${token}.svg.js`)) as { default: string }).default;
  const inner = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, "")
    .replace(/<\/svg>\s*$/, "")
    .replace(/fill="#fff"/g, 'fill="currentColor"')
    .replace(/\s+/g, " ")
    .trim();
  marks[token] = inner;
  console.log(`${token}: ${inner.length} chars`);
}
writeFileSync(
  out,
  `// Generated by scripts/marks.ts from @web3icons/core (MIT). Do not edit.\nexport const ASSET_MARKS = ${JSON.stringify(marks, null, 2)} as const;\n`,
);
